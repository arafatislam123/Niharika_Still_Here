// Prints docs/RECORDING_GUIDE.md: the exact narration script for each cinema-mode film,
// taken from the site's own data so recordings always match the subtitles.
// Run: npx vite-node scripts/recording-script.ts
import fs from 'node:fs';
import { artifacts } from '../src/data/artifacts';
import { CINEMA_ARTIFACTS } from '../src/cinema/available';
import { localizeArtifact } from '../src/i18n';

const strip = (title: string) => title.replace(/^[^:]+:\s*/, '');
let out = `# Recording guide: human narration for cinema mode

Generated by \`scripts/recording-script.ts\`. Do not edit by hand.

## নির্দেশনা (বাংলায়)

1. শান্ত ঘরে ফোনের ভয়েস রেকর্ডার দিয়ে রেকর্ড করো। মুখ থেকে ফোন প্রায় এক হাত দূরে রাখো।
2. প্রতিটি অধ্যায় **আলাদা ফাইলে** রেকর্ড করো। নিচের লেখা হুবহু পড়ো, কারণ এটাই পর্দার সাবটাইটেল।
3. ধীরে, আনন্দ নিয়ে, গল্প বলার মতো করে পড়ো। প্রথমে অধ্যায়ের নাম, একটু থেমে তারপর গল্প।
4. ফাইলগুলো **MP3** করে ঠিক নিচের নামে সেভ করো, যেমন \`bn-1.mp3\`, \`bn-2.mp3\`…
5. ফাইলগুলো রাখো: \`public/audio/narration/<অভিযাত্রী>/\` ফোল্ডারে।
6. \`src/cinema/available.ts\`-এ \`RECORDED_NARRATION\`-এ সেই ভাষা যোগ করো, যেমন \`opportunity: ['bn']\`।
   (অথবা ফাইলগুলো Claude-কে দিলে সে যোগ করে দেবে।)

## Instructions (English)

Record each chapter as a separate MP3, reading the text below exactly (it is the on-screen
subtitle). Save as \`public/audio/narration/<artifact>/<lang>-<chapter>.mp3\` and add the
language to \`RECORDED_NARRATION\` in \`src/cinema/available.ts\`.
`;

for (const raw of artifacts.filter((a) => CINEMA_ARTIFACTS.has(a.id))) {
  out += `\n---\n\n# ${raw.name} (\`${raw.id}\`)\n`;
  for (const lang of ['bn', 'en'] as const) {
    const a = localizeArtifact(raw, lang);
    out += `\n## ${lang === 'bn' ? 'বাংলা' : 'English'}\n`;
    a.chapters.forEach((c, i) => {
      out += `\n### \`public/audio/narration/${a.id}/${lang}-${i + 1}.mp3\`\n\n**${strip(c.title)}।** ${c.text}\n`;
    });
  }
}
fs.writeFileSync('docs/RECORDING_GUIDE.md', out.replace(/।\*\* (?=[A-Z“])/g, '.** '));
console.log('wrote docs/RECORDING_GUIDE.md');
